/** „1 člověk", „3 lidé", „5 lidí" — české tvary podle počtu. */
export function people(count: number): string {
  if (count === 1) return "1 člověk";
  if (count >= 2 && count <= 4) return `${count} lidé`;
  return `${count} lidí`;
}

/** `t("debt.owesYou", { name: "Petr" })` → „Petr ti dluží" */
export function t(key: string, vars?: Record<string, string | number>): string {
  const template = cs[key];
  if (template === undefined) throw new Error(`Chybí překlad pro klíč: ${key}`);
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) =>
    name in vars ? String(vars[name]) : `{${name}}`,
  );
}
